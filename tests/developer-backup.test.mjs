import test from 'node:test';
import assert from 'node:assert/strict';
import { PGlite } from '@electric-sql/pglite';
import { createArchiveCodec, createBackupOperation, readOperationBody, MAX_REQUEST_BYTES, restoreOrder } from '../supabase/functions/_shared/developerBackup.js';
import { createDeveloperDatabase } from '../supabase/functions/_shared/developerDatabase.js';
import { postgresWireParameters } from './helpers/postgres-wire.mjs';

const owner = '11111111-1111-4111-8111-111111111111';
const other = '22222222-2222-4222-8222-222222222222';
const tankId = '33333333-3333-4333-8333-333333333333';
const codec = () => createArchiveCodec({ secret: 'ab'.repeat(32), project: 'https://qa.supabase.invalid' });
function context(body, userId = owner) {
  return { userId, request: new Request('https://qa.invalid/', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(body) }) };
}
async function fixture() {
  const pg = new PGlite();
  await pg.exec(`
    create schema auth;
    create table auth.users (id uuid primary key);
    insert into auth.users values ('${owner}'), ('${other}');
    create table profiles (id uuid primary key references auth.users, name text);
    create table tanks (id uuid primary key, user_id uuid not null references profiles,
      tank_name text not null, depth numeric, raw_status text, updated_at timestamptz);
    create table sensor_readings (id bigint primary key, tank_id uuid references tanks, water_depth_cm numeric, raw_payload jsonb);
    create table device_commands (id int primary key, status text);
    create table tank_automation_settings (id int primary key, auto_water_enabled boolean);
    create table push_tokens (id int primary key, token text);
    create table turbidity_readings (id bigint generated by default as identity primary key, voltage numeric);
    create table unrelated_private_table (id int);
    create function replay_command() returns trigger language plpgsql as $$ begin
      insert into device_commands values (99,'pending'); return new; end $$;
    create trigger sensor_side_effect after insert or update on sensor_readings for each row execute function replay_command();
    insert into profiles values ('${owner}','Owner'),('${other}','Other farmer');
    insert into tanks values ('${tankId}','${other}','Farmer tank',0.6,'Safe Ideal','2026-01-01T00:00:00Z');
    insert into sensor_readings values (9007199254740993,'${tankId}',0.600000000000000001,'{"raw":"unchanged"}');
    delete from device_commands;
    insert into device_commands values (1,'completed');
    insert into tank_automation_settings values (1,false);
    insert into push_tokens values (1,'qa-only-token');
    insert into turbidity_readings values (100,2.1234567890123456789);
  `);
  const sql = { begin: (options, callback) => pg.transaction(async tx => {
    if (options) await tx.exec(`set transaction ${options}`);
    return callback({ unsafe: async (query, parameters) => (await tx.query(query, postgresWireParameters(query, parameters))).rows });
  }) };
  const database = createDeveloperDatabase(sql);
  let time = Date.now();
  const archiveCodec = codec();
  return { pg, database, codec: archiveCodec, advance: ms => { time += ms; },
    export: () => createBackupOperation({ purpose: 'backup', database, codec: archiveCodec, now: () => time })(context({ action: 'export' })),
    restore: (body, userId) => createBackupOperation({ purpose: 'restore', database, codec: archiveCodec, now: () => time })(context(body, userId)),
  };
}

test('encrypted backups are project-bound, authenticated and never contain readable row data', async () => {
  const engine = codec();
  const value = { kind: 'application-backup', private: 'private customer row' };
  const sealed = await engine.seal(value);
  assert.doesNotMatch(JSON.stringify(sealed), /customer|private/);
  assert.deepEqual(await engine.open(sealed), value);
  await assert.rejects(engine.open({ ...sealed, ciphertext: 'AAAA' }), /invalid/);
  await assert.rejects(createArchiveCodec({ secret: 'cd'.repeat(32), project: 'https://qa.supabase.invalid' }).open(sealed));
  await assert.rejects(createArchiveCodec({ secret: 'ab'.repeat(32), project: 'https://other.invalid' }).open(sealed));
  assert.throws(() => createArchiveCodec({ secret: '', project: 'qa' }), /configuration/);
});

test('real PostgreSQL snapshot includes all farmers, excludes Auth and unknown tables, preserves raw precision', async t => {
  const f = await fixture(); t.after(() => f.pg.close());
  const result = await f.export();
  const archive = await f.codec.open(result.backup);
  assert.equal(archive.tables.find(table => table.name === 'profiles').rows.length, 2);
  assert.match(archive.tables.find(table => table.name === 'sensor_readings').rows[0], /9007199254740993/);
  assert.match(archive.tables.find(table => table.name === 'sensor_readings').rows[0], /0.600000000000000001/);
  assert.match(archive.tables.find(table => table.name === 'tanks').rows[0], /Safe Ideal/);
  assert.deepEqual(result.excludedTables, ['unrelated_private_table']);
  assert.ok(!archive.tables.some(table => table.name === 'users'));
  assert.equal(result.tables.find(table => table.name === 'device_commands').restore, false);
});

test('preview is read-only; merge restore preserves newer IDs, raw readings, live queues, automation and FK ordering', async t => {
  const f = await fixture(); t.after(() => f.pg.close());
  const { backup } = await f.export();
  await f.pg.exec(`update tanks set tank_name='Changed'; delete from sensor_readings;
    update device_commands set status='live'; update tank_automation_settings set auto_water_enabled=true;
    update push_tokens set token='current-token';
    insert into tanks(id,user_id,tank_name) values ('44444444-4444-4444-8444-444444444444','${owner}','Newer tank');`);
  const preview = await f.restore({ action: 'preview', backup });
  assert.equal(preview.tables.find(table => table.name === 'tanks').updated, 1);
  assert.equal(preview.tables.find(table => table.name === 'sensor_readings').inserted, 1);
  assert.ok(preview.recoveryBackup.ciphertext);
  assert.equal((await f.pg.query('select tank_name from tanks where id=$1', [tankId])).rows[0].tank_name, 'Changed');
  const result = await f.restore({ action: 'apply', backup, previewToken: preview.previewToken, confirmation: 'RESTORE' });
  assert.equal(result.restored, true);
  assert.equal((await f.pg.query('select count(*)::int as count from tanks')).rows[0].count, 2);
  assert.equal((await f.pg.query('select tank_name from tanks where id=$1', [tankId])).rows[0].tank_name, 'Farmer tank');
  assert.equal((await f.pg.query('select water_depth_cm::text as value from sensor_readings')).rows[0].value, '0.600000000000000001');
  assert.deepEqual((await f.pg.query('select status from device_commands')).rows, [{ status: 'live' }]);
  assert.equal((await f.pg.query('select auto_water_enabled from tank_automation_settings')).rows[0].auto_water_enabled, true);
  assert.equal((await f.pg.query('select token from push_tokens')).rows[0].token, 'current-token');
  assert.equal((await f.pg.query("select tgenabled from pg_trigger where tgname='sensor_side_effect'")).rows[0].tgenabled, 'O');
  assert.equal((await f.pg.query('insert into turbidity_readings(voltage) values(3) returning id::text')).rows[0].id, '101');
});

test('preview proof cannot be skipped, reused by another account, expired, or applied after affected data changes', async t => {
  const f = await fixture(); t.after(() => f.pg.close());
  const { backup } = await f.export();
  const preview = await f.restore({ action: 'preview', backup });
  await assert.rejects(f.restore({ action: 'apply', backup, confirmation: 'RESTORE' }));
  await assert.rejects(f.restore({ action: 'apply', backup, previewToken: preview.previewToken, confirmation: 'yes' }), /RESTORE/);
  await assert.rejects(f.restore({ action: 'apply', backup, previewToken: preview.previewToken, confirmation: 'RESTORE' }, other), /expired or changed/);
  await f.pg.exec("update profiles set name='Changed after preview'");
  await assert.rejects(f.restore({ action: 'apply', backup, previewToken: preview.previewToken, confirmation: 'RESTORE' }), /changed after preview/);
  f.advance(121000);
  await assert.rejects(f.restore({ action: 'apply', backup, previewToken: preview.previewToken, confirmation: 'RESTORE' }), /expired/);
});

