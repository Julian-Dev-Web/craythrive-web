test('constraint failure rolls back earlier tables and trigger suppression; no partial restore', async t => {
  const f = await fixture(); t.after(() => f.pg.close());
  const exported = await f.export();
  const archive = await f.codec.open(exported.backup);
  const tank = archive.tables.find(table => table.name === 'tanks');
  tank.rows[0] = JSON.stringify({ ...JSON.parse(tank.rows[0]), user_id: '99999999-9999-4999-8999-999999999999' });
  const backup = await f.codec.seal(archive);
  await f.pg.exec("update profiles set name='Current name'");
  const preview = await f.restore({ action: 'preview', backup });
  await assert.rejects(f.restore({ action: 'apply', backup, previewToken: preview.previewToken, confirmation: 'RESTORE' }));
  assert.ok((await f.pg.query('select name from profiles')).rows.every(row => row.name === 'Current name'));
  assert.equal((await f.pg.query("select tgenabled from pg_trigger where tgname='sensor_side_effect'")).rows[0].tgenabled, 'O');
  assert.equal((await f.pg.query('select count(*)::int as count from device_commands')).rows[0].count, 1);
});

test('schema drift, duplicate keys, unexpected tables and columns reject restore', async t => {
  const f = await fixture(); t.after(() => f.pg.close());
  const { backup } = await f.export();
  for (const mutate of [
    archive => { archive.tables[0].name = 'auth.users'; },
    archive => { const table = archive.tables.find(table => table.name === 'profiles'); table.rows.push(table.rows[0]); },
    archive => { const table = archive.tables.find(table => table.name === 'profiles'); table.rows[0] = '{"id":"x","unexpected":true}'; },
  ]) {
    const archive = await f.codec.open(backup); mutate(archive);
    await assert.rejects(f.restore({ action: 'preview', backup: await f.codec.seal(archive) }));
  }
  await f.pg.exec('alter table profiles add column new_field text');
  await assert.rejects(f.restore({ action: 'preview', backup }), /schema changed/);
});

test('request size/content limits and cyclic relations fail closed', async () => {
  await assert.rejects(readOperationBody(new Request('https://qa.invalid', { method: 'POST', body: '{}' })), /JSON request/);
  await assert.rejects(readOperationBody(new Request('https://qa.invalid', { method: 'POST', headers: { 'Content-Type': 'application/json', 'Content-Length': String(MAX_REQUEST_BYTES + 1) }, body: '{}' })), /too large/);
  await assert.rejects(readOperationBody(new Request('https://qa.invalid', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: '{broken' })), /Invalid JSON/);
  assert.throws(() => restoreOrder([{ name: 'a' }, { name: 'b' }], [{ table: 'a', parent: 'b' }, { table: 'b', parent: 'a' }]), /cyclic/);
});
